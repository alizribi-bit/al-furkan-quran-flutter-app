enum MatnId { tuhfat, shatibiyyah }

enum MutunDisplayMode { diwan, study, memorize }

enum MutunMaskLevel { secondHemistich, fullLine, visible }

class MatnLine {
  final int number;
  final String first; // الصدر
  final String second; // العجز
  final String note; // فائدة تجويدية أو قرائية
  final String? tag;

  const MatnLine({
    required this.number,
    required this.first,
    required this.second,
    required this.note,
    this.tag,
  });
}

class MatnChapter {
  final String id;
  final int index;
  final String title;
  final String subtitle;
  final String summary;
  final List<MatnLine> lines;

  const MatnChapter({
    required this.id,
    required this.index,
    required this.title,
    required this.subtitle,
    required this.summary,
    required this.lines,
  });
}

class MatnVoice {
  final String id;
  final String name;
  final String title;
  final String style;
  final bool isChapterized;
  final String? fullAudioUrl;
  final Map<String, String>? chapterAudioMap;

  const MatnVoice({
    required this.id,
    required this.name,
    required this.title,
    required this.style,
    required this.isChapterized,
    this.fullAudioUrl,
    this.chapterAudioMap,
  });

  String resolveUrl(String chapterId) {
    if (isChapterized &&
        chapterAudioMap != null &&
        chapterAudioMap!.containsKey(chapterId)) {
      return chapterAudioMap![chapterId]!;
    }
    return fullAudioUrl ?? '';
  }
}

class ShatibiyyahSymbol {
  final String code;
  final String name;
  final String type; // 'individual' | 'group' | 'word'
  final String details;

  const ShatibiyyahSymbol({
    required this.code,
    required this.name,
    required this.type,
    required this.details,
  });
}

class MatnBook {
  final MatnId id;
  final String title;
  final String fullTitle;
  final String author;
  final String era;
  final String totalLinesLabel;
  final String discipline;
  final List<MatnVoice> voices;
  final List<MatnChapter> chapters;

  const MatnBook({
    required this.id,
    required this.title,
    required this.fullTitle,
    required this.author,
    required this.era,
    required this.totalLinesLabel,
    required this.discipline,
    required this.voices,
    required this.chapters,
  });

  int get totalLines => chapters.fold(0, (sum, c) => sum + c.lines.length);
}

String toArabicIndic(int num) {
  const digits = ['٠', '١', '٢', '٣', '٤', '٥', '٦', '٧', '٨', '٩'];
  return num
      .toString()
      .split('')
      .map((c) {
        final code = c.codeUnitAt(0);
        if (code >= 48 && code <= 57) return digits[code - 48];
        return c;
      })
      .join();
}

